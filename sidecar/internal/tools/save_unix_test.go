package tools

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

// A save is owner-only.
func TestASaveIsOwnerOnly(t *testing.T) {
	path, ok := SaveTo(testChatDir(filepath.Join(t.TempDir(), "c1")))("text")
	require.True(t, ok)

	info, err := os.Stat(path)
	require.NoError(t, err)
	assert.Equal(t, os.FileMode(0o600), info.Mode().Perm())
}
